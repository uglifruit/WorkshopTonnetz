// fastmath.h — fixed-point primitives for the 48 kHz path.
//
// Ported from WorkshopOcarina/fastmath.h and WorkshopShepard's pitch table.
// Integer-only: the RP2040 has no FPU, and the build's -Wdouble-promotion /
// -Wfloat-conversion catch any float that sneaks in.
//
// Conventions:
//   Q15   int32, 32768 == 1.0     signed unit values (waveforms)
//   Q16   int32, 65536 == 1.0     semitone pitches (MIDI note << 16)
//   Q30   int32, 2^30 == 1.0      envelope levels
//   phase uint32, full range == one cycle, wraps for free

#pragma once
#include <stdint.h>
#include "platform.h"
#include "dsp_config.h"

namespace tonnetz {

/// Quarter-wave sine, Q15, generated by DspInit(). 258 entries, the last one
/// padding: fast_sin() mirrors the index on odd quadrants and can then read
/// entry 257 on an exact-boundary phase (multiplied by zero, but a read past
/// the end all the same). WorkshopOcarina found this; do not trim it to 257.
/// A plain global, not a header static, so it lands in RAM.
extern int16_t gSinTable[258];

/// Phase increment per sample for each MIDI note at 48 kHz.
extern uint32_t gNoteInc[129];

/// Builds the tables. Call once at boot, before the audio starts.
void DspInit();

static inline int32_t __attribute__((always_inline)) fast_sin(uint32_t phase)
{
	uint32_t quadrant = phase >> 30;
	uint32_t frac     = (phase >> 6) & 0xFFFFFF;
	uint32_t idx      = frac >> 16;
	uint32_t mu       = frac & 0xFFFF;
	if (quadrant & 1)
	{
		idx = 255 - idx;
		mu  = 65536 - mu;
		if (mu == 65536) { mu = 0; idx++; }
	}
	int32_t a = gSinTable[idx];
	int32_t b = gSinTable[idx + 1];
	int32_t v = a + (((b - a) * static_cast<int32_t>(mu)) >> 16);
	return (quadrant & 2) ? -v : v;
}

/// Triangle from phase, Q15, in phase with fast_sin (peaks at a quarter cycle).
static inline int32_t __attribute__((always_inline)) fast_tri(uint32_t phase)
{
	const uint32_t p = (phase + 0x40000000u) >> 16;   // shift so it rises through 0 at phase 0
	const int32_t t = (p < 32768) ? static_cast<int32_t>(p) : static_cast<int32_t>(65535 - p);
	return (t - 16384) * 2;
}

/// Sine/triangle blend, Q15. mix 0 = sine, 32768 = triangle.
static inline int32_t __attribute__((always_inline)) wave(uint32_t phase, int32_t mixQ15)
{
	const int32_t s = fast_sin(phase);
	return s + (((fast_tri(phase) - s) * mixQ15) >> 15);
}

/// Q16 semitone pitch -> phase increment. Exact on semitones; between them
/// linear in frequency with 8-bit weight (< 1 cent off a true exponential).
static inline uint32_t __attribute__((always_inline)) PitchToInc(int32_t pitchQ16)
{
	if (pitchQ16 < (kPitchMin << 16)) pitchQ16 = kPitchMin << 16;
	if (pitchQ16 > (kPitchMax << 16)) pitchQ16 = kPitchMax << 16;
	const int32_t n = pitchQ16 >> 16;
	const uint32_t f8 = static_cast<uint32_t>(pitchQ16 >> 8) & 0xFFu;
	const uint32_t a = gNoteInc[n];
	return a + (((gNoteInc[n + 1] - a) * f8) >> 8);
}

static inline int16_t __attribute__((always_inline)) clamp12(int32_t v)
{
	if (v < -2048) return -2048;
	if (v > 2047) return 2047;
	return static_cast<int16_t>(v);
}

} // namespace tonnetz
